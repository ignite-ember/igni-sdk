class SdkDocs:
    """The pages and their index, and whether what is checked in is current."""

    def __init__(self, root: Path = ROOT, readmes: dict[str, str] | None = None) -> None:
        self.root = root
        #: README text by package, to generate from other READMEs than the checked-in ones.
        self.readmes = readmes or {}
        self.report: dict[str, Any] = {}

    def _readme(self, package: Package) -> str:
        if package.name in self.readmes:
            return self.readmes[package.name]
        return (self.root / package.path / "README.md").read_text(encoding="utf-8")

    def _project(self, package: Package) -> dict[str, Any]:
        """What a package says of itself: its version, its summary, its source."""
        if package.kind == "npm":
            data = json.loads(
                (self.root / package.path / "package.json").read_text(encoding="utf-8")
            )
            return {
                "version": data["version"],
                "description": data["description"],
                "source": _npm_source(data),
            }
        data = tomllib.loads(
            (self.root / package.path / "pyproject.toml").read_text(encoding="utf-8")
        )
        project: dict[str, Any] = data["project"]
        return {
            "version": project["version"],
            "description": project["description"],
            "source": project.get("urls", {}).get("Source", ""),
        }

    def pages(self) -> list[Page]:
        contract = RpcContract.read(self.root / CONTRACT_FILE.relative_to(ROOT))
        out: list[Page] = []
        for package in PACKAGES:
            project = self._project(package)
            text = self._readme(package)
            if package.kind == "npm":
                site = ReadmeSite(package, text, description=project["description"])
                guide = site.pages()
                out += guide
                out += npm_pages(package, len(guide), self.report, self.root)
                continue
            if package.name == "igni-client":
                readme = ReadmePages(text, f"{package.path}/README.md")
                errors = read_errors(self.root / package.path / "src/igni_client/errors.py")
                client = ClientReference(contract, errors, readme)
                start_at, end_at = text.find(README_START), text.find(README_END)
                if start_at < 0 or end_at < start_at:
                    raise DocsError(f"{package.path}/README.md has no generated API reference")
                # On the site, the README's generated reference is the reference pages.
                spliced = (
                    text[:start_at] + client.readme_replacement() + text[end_at + len(README_END) :]
                )
                site = ReadmeSite(
                    package,
                    spliced,
                    description=project["description"],
                    extra_anchors=client.readme_anchors(),
                )
                guide = site.pages()
                start = len(guide)
                reference = client.reference_pages(start)
                start += len(reference)
                out += guide + reference
                out.append(client.access_page(start))
                out.append(client.models_page(start + 1))
                out.append(client.events_page(start + 2))
                out.append(client.errors_page(start + 3))
                self.report["igni-client"] = {
                    "missing_meanings": sorted(set(client.missing_meanings)),
                    "undocumented_models": client.undocumented_models,
                }
            else:
                site = ReadmeSite(package, text, description=project["description"])
                guide = site.pages()
                out += guide
                out += python_pages(package, len(guide), self.report)
        seen: set[tuple[str, str]] = set()
        for page in out:
            key = (page.package, page.slug)
            if key in seen:
                raise DocsError(f"two pages are {page.package}/{page.slug}")
            seen.add(key)
        return out

    def index(self, pages: list[Page]) -> str:
        packages = []
        for package in PACKAGES:
            project = self._project(package)
            entry: dict[str, Any] = {
                "name": package.site,
                "registry": package.registry,
                "registryName": package.name,
                "registryUrl": package.registry_url,
                "install": package.install,
                "importName": package.module,
                "version": project["version"],
                "description": project["description"],
                "source": project["source"],
            }
            if package.kind == "python":
                entry["pypi"] = package.registry_url
            packages.append(entry)
        data = {
            "generated_by": "igni-sdk tools/sdk_docs.py (make sdk-docs); do not edit",
            "packages": packages,
            "pages": [
                {
                    "package": p.package,
                    "slug": p.slug,
                    "title": p.title,
                    "description": p.description,
                    "category": p.category,
                    "order": p.order,
                    "file": p.file,
                    "sections": p.sections(),
                }
                for p in pages
            ],
        }
        return json.dumps(data, indent=2, ensure_ascii=False) + "\n"

    def outputs(self) -> dict[Path, str]:
        pages = self.pages()
        out = {self.root / OUTPUT / p.file: p.text() for p in pages}
        out[self.root / INDEX] = self.index(pages)
        return out

    def write(self) -> list[Path]:
        outputs = self.outputs()
        written: list[Path] = []
        for path, text in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                written.append(path)
        for path in sorted((self.root / OUTPUT).rglob("*")):
            if path.is_file() and path not in outputs:
                path.unlink()
                written.append(path)
        return written

    def stale(self) -> list[Path]:
        outputs = self.outputs()
        stale = [
            path
            for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        directory = self.root / OUTPUT
        if directory.exists():
            stale += [p for p in sorted(directory.rglob("*")) if p.is_file() and p not in outputs]
        return stale


def main() -> int:
    docs = SdkDocs()
    for path in docs.write():
        print("wrote" if path.exists() else "removed", path.relative_to(ROOT))
    for package, notes in docs.report.items():
        for key, value in notes.items():
            if value:
                print(f"{package}: {key}: {value}")
    return 0


