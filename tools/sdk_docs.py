@dataclass
class ErrorClass:
    name: str
    bases: list[str]
    doc: str

    @property
    def summary(self) -> str:
        return self.doc.split("\n\n", 1)[0].replace("\n", " ")


def read_errors(path: Path) -> list[ErrorClass]:
    """igni-client's exceptions, read from its ``errors.py`` without importing it."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    out: list[ErrorClass] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            bases = [b.id for b in node.bases if isinstance(b, ast.Name)]
            out.append(ErrorClass(node.name, bases, ast.get_docstring(node) or ""))
    return out


class ClientReference:
    """igni-client's reference pages, from the contract and the generator's plan."""

    PACKAGE = "igni-client"

    def __init__(self, contract: RpcContract, errors: list[ErrorClass], readme: ReadmePages):
        self.plan = Plan(contract)
        self.contract = self.plan.contract
        self.types = self.plan.types
        self.api = ApiGenerator(self.plan)
        # Generating the API names the unions the models use.
        self.api.generate()
        self.errors = {e.name: e for e in errors}
        self.error_order = [e.name for e in errors]
        self.readme = readme
        self.placements = self._placements()
        self.page_of = self._pages()
        self.messages = self.plan.message_of_def()
        self.links: dict[str, str] = {}
        self._link_everything()
        self.missing_meanings: list[str] = []
        self._wire_properties: set[str] | None = None

    # ── What is where ──

    def _placements(self) -> dict[str, Placement]:
        out = dict(self.plan.placements)
        for wire, (_, path) in MESSAGE_METHODS.items():
            out[wire] = Placement.of(wire, path)
        return out

    def _pages(self) -> dict[str, str]:
        """Wire name → the slug of the page it is on.

        A page takes a method named by its path (``session.run_shell``), and every
        method of a namespace it names (``igni.processes``) that no page names."""
        paths = {p.path for p in self.placements.values()}
        groups = {p.group for p in self.placements.values()}
        named = {s for _, _, sources in REFERENCE_PAGES for s in sources if s in paths}
        taken: dict[str, list[str]] = {}
        for slug, _, sources in REFERENCE_PAGES:
            unknown = [s for s in sources if s not in paths and s not in groups]
            if unknown:
                raise DocsError(f"REFERENCE_PAGES' {slug} names what igni-client lacks: {unknown}")
            for wire, placement in self.placements.items():
                if placement.path in sources or (
                    placement.group in sources and placement.path not in named
                ):
                    taken.setdefault(wire, []).append(slug)
        unplaced = sorted(set(self.placements) - set(taken))
        if unplaced:
            raise DocsError(
                "methods no page in REFERENCE_PAGES (tools/client_names.py) takes: "
                + ", ".join(self.placements[w].path for w in unplaced)
            )
        twice = {w: s for w, s in taken.items() if len(s) > 1}
        if twice:
            raise DocsError(f"methods on two reference pages: {twice}")
        return {wire: slugs[0] for wire, slugs in taken.items()}

    def _link_everything(self) -> None:
        for name in sorted(self.plan.defs_in | self.plan.defs_out):
            cls = self.types.class_name(name)
            page = EVENTS_PAGE if name in self.messages else MODELS_PAGE
            self.links[cls] = url(self.PACKAGE, page, site_id(cls))
        # An argument model's fields are its method's parameters: it links there.
        for wire in self.plan.placements:
            args = self.contract.ref_name(self.contract.methods[wire].args)
            if args is not None:
                self.links[self.types.class_name(args)] = self._method_url(wire)
        for channel in self.contract.push_channels:
            cls = push_class(channel)
            self.links[cls] = url(self.PACKAGE, EVENTS_PAGE, site_id(cls))
        for alias in self.types.unions:
            self.links[alias] = url(self.PACKAGE, MODELS_PAGE, site_id(alias))
        for name in self.errors:
            self.links[name] = url(self.PACKAGE, ERRORS_PAGE, site_id(name))
        for wire in FOLLOWED:
            alias = self.api.event_alias(wire)
            placement = self.placements[wire]
            self.links[alias] = url(
                self.PACKAGE, self.page_of[wire], site_id(self.heading(placement))
            )
        call = self._readme_anchor("API reference", "Call")
        if call:
            self.links["Call"] = call

    def _readme_anchor(self, section: str, heading: str) -> str | None:
        for h in self.readme.headings:
            if h.section == section and plain(h.text) == heading and h.level > 2:
                return url(self.PACKAGE, site_id(section), site_id(h.text))
        return None

    # ── Rendering pieces ──

    def type_md(self, annotation: str, *, in_table: bool = False) -> str:
        """An annotation in code, with every type the reference documents linked."""
        annotation = annotation.replace("builtins.", "")
        parts = re.split(r"([A-Za-z_][A-Za-z0-9_]*)", annotation)
        out: list[str] = []
        pending = ""
        for part in parts:
            if part in self.links:
                if pending:
                    out.append(f"`{pending}`")
                    pending = ""
                out.append(f"[`{part}`]({self.links[part]})")
            else:
                pending += part
        if pending:
            out.append(f"`{pending}`")
        text = "".join(out)
        return text.replace("|", "\\|") if in_table else text

    @staticmethod
    def heading(placement: Placement) -> str:
        return f"{placement.path}()"

    def _method_url(self, wire: str) -> str:
        placement = self.placements[wire]
        return url(self.PACKAGE, self.page_of[wire], site_id(self.heading(placement)))

    def method_link(self, wire: str) -> str:
        return f"[`{self.placements[wire].path}()`]({self._method_url(wire)})"

    def wire_properties(self) -> set[str]:
        """Every field name the contract spells in the wire's camelCase."""
        if self._wire_properties is None:
            names: set[str] = set()
            for schema in self.contract.defs.values():
                names.update(schema.get("properties", {}))
            self._wire_properties = names
        return self._wire_properties

    def prose(self, text: str) -> str:
        """The contract's prose for a Python page: it names the Python call or attribute.

        igni-core writes its docs for the wire: ``whenToUse`` is the field
        and ``run_workflow`` the method. A Python reader finds
        ``when_to_use`` and ``session.workflows.run()``, so a name in code
        font is said the way the Python API says it.
        """
        text = rst(text)
        fields = self.wire_properties()

        def name(match: re.Match[str]) -> str:
            token = match.group(1)
            placement = self.placements.get(token)
            if placement is not None and "_" in token and token not in fields:
                return f"`{placement.path}()`"
            if token in fields and field_name(token) != token:
                return f"`{field_name(token)}`"
            return match.group(0)

        return re.sub(r"`([A-Za-z_][A-Za-z0-9_]*)`", name, text)

    def meaning(self, wire: str, prop: str, schema: dict[str, Any], doc: str) -> str:
        """What a parameter is: its own description, else what the method's doc says of it."""
        if schema.get("description"):
            return self.prose(schema["description"])
        text = " ".join(doc.split())
        sentences = re.split(r"(?<=[.;:])\s+(?=[A-Z`(*])", text)
        for sentence in sentences:
            if f"``{prop}``" in sentence:
                return self.prose(sentence)
        self.missing_meanings.append(f"{wire}.{prop}")
        return "—"

    def default_text(self, default: str | None) -> str:
        return "required" if default is None else f"`{default}`"

    # ── A method ──

    def method(self, wire: str) -> list[str]:
        placement = self.placements[wire]
        if wire in MESSAGE_METHODS:
            return self._message_method(wire, placement)
        method = self.contract.methods[wire]
        params, _ = self.api.params(placement)
        shown = [p for p in params if p.annotation]
        sig = self.api.signature(placement, params).replace("builtins.", "")
        result = self.api.result_type(wire).replace("builtins.", "")
        followed = wire in FOLLOWED
        if followed:
            code = signature(
                f"def {placement.name}", sig, f" -> Call[{result}, {self.api.event_alias(wire)}]"
            )
        else:
            code = signature(f"async def {placement.name}", sig, f" -> {result}")
        doc_paragraphs = method.doc.strip().split("\n\n")
        summary = self.prose(doc_paragraphs[0].replace("\n", " "))
        rest = [self.prose(p) for p in doc_paragraphs[1:]]
        # igni-core's text may open with "Takes no arguments."; the page says
        # it once, in the place a parameter table would be.
        note = ""
        if not shown:
            summary, note = _take_no_arguments(summary)
            taken = [_take_no_arguments(p) for p in rest]
            rest = [text for text, _ in taken]
            note = note or next((n for _, n in taken if n), "")
        out = [f"## {self.heading(placement)}", ""]
        out += [summary, ""] if summary else []
        out += ["```python", code, "```", ""]
        for paragraph in rest:
            out += [paragraph, ""] if paragraph else []
        args_def = self.contract.ref_name(method.args) or ""
        props = self.contract.defs[args_def].get("properties", {}) if args_def else {}
        if shown:
            out += ["| Parameter | Type | Default | Meaning |", "|---|---|---|---|"]
            by_python = {field_name(p): p for p in props}
            for p in shown:
                prop = by_python[p.name]
                meaning = self.meaning(wire, prop, props[prop], method.doc)
                out.append(
                    f"| `{p.name}` | {self.type_md(p.annotation.replace('builtins.', ''), in_table=True)} "
                    f"| {self.default_text(p.default)} | {cell(meaning)} |"
                )
            out.append("")
        else:
            hidden = (
                " (`session_id` is this session's own)"
                if placement.owner == "session" and wire in OWN_SESSION_ARG
                else ""
            )
            if note:
                hidden = f" ({note}; `session_id` is this session's own)" if hidden else f" ({note})"
            out += [f"Takes no arguments{hidden}.", ""]
        if followed:
            out += [
                f"**Returns** a {self.type_md('Call')} — await it for the result, "
                f"{self.type_md(result)}, or `async with` it to follow its events too.",
                "",
            ]
        else:
            out += [f"**Returns** {self.type_md(result)}.", ""]
        out += self._streams(wire)
        out += self._duration(wire)
        out += self._access(method.access)
        out += self._raises(wire, method.access, followed, sends_only=False)
        out += [
            f"**On the wire** RPC method `{wire}`, scope `{method.scope}`, area "
            f"`{method.area}`; igni answers with `{method.reply}`.",
            "",
        ]
        out += self._example(wire, placement, params)
        return out

    def _streams(self, wire: str) -> list[str]:
        method = self.contract.methods.get(wire)
        if method is None:
            return []
        classes = self.plan.event_classes(wire)
        linked = ", ".join(self.type_md(c) for c in classes)
        channels = ", ".join(f"`{s.removeprefix(PUSH_PREFIX)}`" for s in method.streams)
        out: list[str] = []
        if method.streams:
            if wire in FOLLOWED:
                out += [
                    f"**Events** `{self.api.event_alias(wire)}` is any of {linked} "
                    f"(igni streams {channels}).",
                    "",
                ]
            else:
                out += [
                    f"**Events** while it runs igni also streams {channels} ({linked}). "
                    f"This call does not follow them: {rst(UNFOLLOWED[wire])}",
                    "",
                ]
        if method.may_stream:
            may = ", ".join(f"`{s.removeprefix(PUSH_PREFIX)}`" for s in method.may_stream)
            out += [
                f"**While it runs** it may also cause these pushes: {may}.",
                "",
            ]
        if wire in FOLLOWED:
            out += [
                f"**How they are told apart** {rst(FOLLOWED[wire])}",
                "",
            ]
        out += self._told_apart(wire)
        return out

    def _told_apart(self, wire: str) -> list[str]:
        """How the contract says the call's own events are told from every other call's."""
        method = self.contract.methods.get(wire)
        correlate = method.correlate if method is not None else None
        if correlate is None:
            return []
        place = _PLACE_TEXT.get(correlate.by) or _place_text(correlate.by)
        if correlate.equals:
            return [
                f"**Told apart by** {place} is `{correlate.equals}` — igni's contract says so.",
                "",
            ]
        if correlate.source:
            source = _SOURCE_TEXT.get(correlate.source) or _source_text(correlate.source)
            return [f"**Told apart by** {place} is {source} — igni's contract says so.", ""]
        return [f"**Told apart by** {place}, and by what the call causes.", ""]

    def _duration(self, wire: str) -> list[str]:
        """How long the call takes, and how long the client waits for it."""
        method = self.contract.methods.get(wire)
        if method is None or not method.duration:
            return []
        duration = self.contract.durations.get(method.duration)
        what = rst(duration.doc) if duration is not None else f"`{method.duration}`"
        out = [f"**How long** `{method.duration}` — {what}"]
        if method.timeout_seconds is None:
            out.append("The client waits as long as it takes.")
        else:
            out.append(f"The client waits up to {method.timeout_seconds} seconds.")
        out.append("")
        return out

    def _access(self, access: str) -> list[str]:
        link = url(self.PACKAGE, ACCESS_PAGE)
        if access == "client":
            return [f"**Access** [`client`]({link}) — any connection igni admitted.", ""]
        note = rst(ACCESS_NOTES[access]).removeprefix(f"Access: `{access}`. ")
        return [f"**Access** [`{access}`]({link}) — {note}", ""]

    def _raises(self, wire: str, access: str, followed: bool, *, sends_only: bool) -> list[str]:
        names = ["InvalidArguments"]
        if access != "client":
            names.append("AccessRefused")
        if not sends_only:
            names += ["MethodFailed", "UnknownMethod", "UnexpectedAnswer"]
        names.append("Unavailable")
        if followed:
            names.append("RunInterrupted")
        parts: list[str] = []
        for name in names:
            if name not in self.errors:
                raise DocsError(f"igni-client has no {name} to document")
            link = self.type_md(name)
            if name == "AccessRefused":
                link += f" when this connection does not stand as `{access}`"
            elif name == "RunInterrupted":
                link += " when the connection moves or drops while the call is followed"
            parts.append(link)
        return [
            "**Raises** "
            + " · ".join(parts)
            + f" ([when each is raised]({url(self.PACKAGE, ERRORS_PAGE)}))",
            "",
        ]

    def _example(self, wire: str, placement: Placement, params: Iterable[Any]) -> list[str]:
        code = EXAMPLES.get(wire)
        if code is None:
            code = self.generated_example(wire, placement, list(params))
        if code is None:
            raise DocsError(
                f"{placement.path}() ({wire}) has no example: add one to EXAMPLES in "
                "tools/client_examples.py"
            )
        check_example(placement, list(params), code, wire in MESSAGE_METHODS, self)
        return ["**Example**", "", "```python", code.strip("\n"), "```", ""]

    def generated_example(self, wire: str, placement: Placement, params: list[Any]) -> str | None:
        """An example for a method that only reads and needs no argument."""
        if wire in FOLLOWED or wire in MESSAGE_METHODS or not READS.match(wire):
            return None
        if any(p.annotation and p.default is None for p in params):
            return None
        call = f"await {placement.path}()"
        result = self.contract.methods[wire].result
        ref = self.contract.ref_name(result)
        items = (
            self.contract.ref_name(result.get("items", {}))
            if result.get("type") == "array"
            else None
        )
        if items is not None:
            var = snake(self.types.class_name(items))
            fields = self._first_fields(items)
            shown = ", ".join(f"{var}.{f}" for f in fields) or var
            return f"for {var} in {call}:\n    print({shown})\n"
        if ref is not None and not self.types.is_enum(ref):
            fields = self._first_fields(ref)
            var = _var(placement.name)
            nullable = any(m.get("type") == "null" for m in result.get("anyOf", []))
            shown = ", ".join(f"{var}.{f}" for f in fields) or var
            if nullable:
                return f"{var} = {call}\nif {var} is not None:\n    print({shown})\n"
            return f"{var} = {call}\nprint({shown})\n"
        if any(m.get("type") == "null" for m in result.get("anyOf", [])):
            inner = next(
                (self.contract.ref_name(m) for m in result["anyOf"] if m.get("type") != "null"),
                None,
            )
            if inner:
                fields = self._first_fields(inner)
                var = _var(placement.name)
                shown = ", ".join(f"{var}.{f}" for f in fields) or var
                return f"{var} = {call}\nif {var} is not None:\n    print({shown})\n"
        return f"print({call})\n"

    def _first_fields(self, def_name: str) -> list[str]:
        props = self.contract.defs[def_name].get("properties", {})
        envelope = _ENVELOPE if def_name in self.messages else ()
        names = [p for p in props if p not in envelope]
        preferred = [p for p in names if p in ("id", "name", "status", "pid", "role")]
        chosen = (preferred + [p for p in names if p not in preferred])[:2]
        return [field_name(p) for p in chosen]

    def _message_method(self, wire: str, placement: Placement) -> list[str]:
        reply, _ = MESSAGE_METHODS[wire]
        message = self.contract.messages[wire]
        def_name = self.contract.message_def(wire)
        schema = self.contract.defs[def_name]
        props = {
            p: s
            for p, s in schema.get("properties", {}).items()
            if p not in _ENVELOPE and p != "client_id"
        }
        result = self.types.class_name(self.contract.message_def(reply)) if reply else "None"
        params = []
        for prop, prop_schema in props.items():
            annotation = self.types.annotation(prop_schema, _Imports())
            default = repr(prop_schema["default"]) if "default" in prop_schema else None
            params.append(_Param(prop, annotation, default))
        sig = ", ".join(
            ["self"]
            + [
                f"{p.name}: {p.annotation}" + (f" = {p.default}" if p.default else "")
                for p in params
            ]
        )
        doc = MESSAGE_DOCS.get(wire, message.doc)
        paragraphs = doc.strip().split("\n\n")
        out = [
            f"## {self.heading(placement)}",
            "",
            rst(paragraphs[0].replace("\n", " ")),
            "",
            "```python",
            signature(f"async def {placement.name}", sig, f" -> {result}"),
            "```",
            "",
        ]
        for paragraph in paragraphs[1:]:
            out += [rst(paragraph), ""]
        if params:
            out += ["| Parameter | Type | Default | Meaning |", "|---|---|---|---|"]
            for p in params:
                meaning = self.meaning(wire, p.name, props[p.name], doc)
                out.append(
                    f"| `{p.name}` | {self.type_md(p.annotation, in_table=True)} | "
                    f"{self.default_text(p.default)} | {cell(meaning)} |"
                )
            out.append("")
        out += [f"**Returns** {self.type_md(result)}.", ""]
        out += self._access("client")
        out += self._raises(wire, "client", False, sends_only=not reply)
        answered = f", answered by igni's `{reply}`" if reply else "; igni answers nothing"
        out += [f"**On the wire** the message `{wire}`{answered}.", ""]
        out += self._example(wire, placement, params)
        return out

