    def _used_in(self, names: list[str]) -> str:
        unique = sorted(dict.fromkeys(self.types.class_name(n) for n in names))
        return "**Part of** " + ", ".join(self.type_md(n) for n in unique) + "."

    def fields_table(self, def_name: str) -> list[str]:
        schema = self.contract.defs[def_name]
        props: dict[str, Any] = schema.get("properties", {})
        if not props:
            return ["No fields.", ""]
        required = set(schema.get("required", []))
        described = any(s.get("description") or "const" in s for s in props.values())
        out = (
            ["| Field | Type | Default | Description |", "|---|---|---|---|"]
            if described
            else ["| Field | Type | Default |", "|---|---|---|"]
        )
        for prop, prop_schema in props.items():
            python = field_name(prop)
            name = f"`{python}`" + (f" (wire `{prop}`)" if python != prop else "")
            annotation = self.types.annotation(prop_schema, _Imports())
            if "default" in prop_schema:
                default = f"`{_py(prop_schema['default'])}`"
            elif prop in required:
                default = "required"
            else:
                kind = prop_schema.get("type")
                default = "`{}`" if kind == "object" else "`[]`" if kind == "array" else "`None`"
                # The model says `X | None` for a field that defaults to None.
                if (
                    default == "`None`"
                    and annotation != "None"
                    and not annotation.endswith("| None")
                ):
                    annotation += " | None"
            const = f"always `{prop_schema['const']!r}`. " if "const" in prop_schema else ""
            desc = const + rst(prop_schema.get("description", ""))
            row = f"| {name} | {self.type_md(annotation, in_table=True)} | {default} |"
            out.append(f"{row} {cell(desc)} |" if described else row)
        out.append("")
        return out

    def _model(
        self, name: str, returned_by: dict[str, list[str]], used_in: dict[str, list[str]]
    ) -> tuple[list[str], int]:
        schema = self.contract.defs[name]
        cls = self.types.class_name(name)
        out = [f"### {cls}", ""]
        missing = 0
        if schema.get("description"):
            out += [rst(schema["description"]), ""]
        else:
            missing = 1
        out += self.fields_table(name)
        if name in returned_by:
            out += [
                "**Returned by** "
                + ", ".join(self.method_link(w) for w in returned_by[name])
                + ".",
                "",
            ]
        if name in used_in:
            out += [self._used_in(used_in[name]), ""]
        return out, missing

