    def readme_anchors(self) -> dict[str, tuple[str, str]]:
        """The README's anchors for headings in its generated reference → their page."""
        out: dict[str, tuple[str, str]] = {}
        in_region = False
        seen: dict[str, int] = {}
        from tools.markdown_pages import github_anchor

        group_page: dict[str, str] = {}
        for wire, slug in self.page_of.items():
            group_page.setdefault(self.placements[wire].group, slug)
        for line, code in fenced(self.readme.text.split("\n")):
            if README_START in line:
                in_region = True
            if README_END in line:
                in_region = False
            match = None if code else re.match(r"(#{1,6})\s+(.+?)\s*$", line)
            if not match:
                continue
            base = github_anchor(match.group(2))
            count = seen.get(base, 0)
            seen[base] = count + 1
            anchor = base if count == 0 else f"{base}-{count}"
            if not in_region:
                continue
            text = plain(match.group(2))
            if text in group_page:
                out[anchor] = (group_page[text], "")
            elif text == "Who may call what":
                out[anchor] = (ACCESS_PAGE, "")
            elif text == "Not for clients":
                out[anchor] = (ACCESS_PAGE, "not-for-clients")
        return out


