def url(package: str, slug: str = "", anchor: str = "") -> str:
    """A page's path on the site; the overview is the package's own path.

    ``package`` is the name the site routes the package on
    (``Package.site``), not the name the registry knows it by.
    """
    path = f"{BASE}/{package}" + (f"/{slug}" if slug and slug != "overview" else "")
    return path + (f"#{anchor}" if anchor else "")


def docs_url(package: str) -> str:
    """The package's documentation, absolute: what its README and registry page link to."""
    return SITE + url(package)


def rst(text: str) -> str:
    """igni-core's reStructuredText-flavoured docstrings, as Markdown."""
    text = re.sub(r":(?:class|meth|func|attr|data|mod|exc):`~?([^`]+)`", r"`\1`", text)
    return text.replace("``", "`")


_NO_ARGUMENTS = re.compile(r"Takes no arguments(?: \(([^)]*)\))?\.\s*")


def _take_no_arguments(text: str) -> tuple[str, str]:
    """``text`` without its opening "Takes no arguments.", and what that said in brackets."""
    match = _NO_ARGUMENTS.match(text)
    if match is None:
        return text, ""
    return text[match.end() :], match.group(1) or ""


def cell(text: str) -> str:
    """``text`` fit for one cell of a Markdown table."""
    return " ".join(text.split()).replace("|", "\\|")


def _npm_source(data: dict[str, Any]) -> str:
    """The repository an npm package's source is in, as a URL."""
    repository = data.get("repository", {})
    url = repository if isinstance(repository, str) else repository.get("url", "")
    if url.startswith("git+"):
        url = url[len("git+") :]
    if url.endswith(".git"):
        url = url[: -len(".git")]
    return url


# ── The READMEs ─────────────────────────────────────────────────────────


#: Sections of a README that are not pages: its table of contents, which the
#: site's sidebar replaces.
SKIPPED_SECTIONS = frozenset({"Contents"})


class ReadmeSite:
    """One package README, as the site's guide pages."""

    def __init__(
        self,
        package: Package,
        text: str,
        *,
        description: str,
        extra_anchors: dict[str, tuple[str, str]] | None = None,
    ) -> None:
        self.package = package
        self.description = description
        self.readme = ReadmePages(text, f"{package.path}/README.md")
        #: GitHub anchors of headings the site moves elsewhere → (page slug, anchor).
        self.extra = extra_anchors or {}
        self.slugs: dict[str | None, str] = {None: "overview"}
        for section in self.readme.sections:
            if section.title in SKIPPED_SECTIONS:
                continue
            self.slugs[section.title] = site_id(section.title)

    def resolve(self, current: str, anchor: str) -> str:
        """Where the README's ``#anchor`` is on the site, from page ``current``."""
        anchors = self.readme.anchors()
        if anchor in self.extra:
            slug, target = self.extra[anchor]
        elif anchor in anchors:
            section, target = anchors[anchor]
            if section not in self.slugs:
                raise PageError(
                    f"{self.readme.path} links to #{anchor}, in a section that is not a page"
                )
            slug = self.slugs[section]
        else:
            raise PageError(f"{self.readme.path} links to #{anchor}, which it has no heading for")
        if slug == current:
            return f"#{target}" if target else "#"
        return url(self.package.site, slug, target)

    def pages(self, start: int = 0) -> list[Page]:
        name = self.package.site
        pages: list[Page] = []
        intro = [
            line
            for line in self.readme.intro
            if f"{SITE}{BASE}/{name}" not in line  # the README's link to these pages
        ]
        pages.append(
            Page(
                name,
                "overview",
                "Overview",
                self.description,
                GUIDE,
                start,
                tidy(rewrite_links(intro, lambda a: self.resolve("overview", a), self.readme.path)),
                source=f"{self.readme.path} (before its first section)",
            )
        )
        order = start
        for section in self.readme.sections:
            if section.title in SKIPPED_SECTIONS:
                continue
            order += 1
            slug = self.slugs[section.title]
            lines = section.lines
            body = rewrite_links(
                lift(lines), lambda a, s=slug: self.resolve(s, a), self.readme.path
            )
            pages.append(
                Page(
                    name,
                    slug,
                    plain(section.title),
                    first_sentences("\n".join(section.lines)),
                    GUIDE,
                    order,
                    tidy(body),
                    source=f"{self.readme.path}, “{plain(section.title)}”",
                )
            )
        return pages


