"""One page of the SDKs' documentation on the site, and where a page is served.

Every part of the generator (``tools/sdk_docs.py``) hands back pages of this
one shape: the README's guide pages (``tools/readme_site.py``), igni-client's
reference (``tools/client_site.py``) and the other packages' reference
(``tools/package_reference.py``).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from pydantic import BaseModel, Field

from tools.markdown_pages import fenced, plain, site_id

#: Where the pages are served, and the site.
SITE = "https://ignite-ember.sh"
BASE = "/docs/sdk"

#: A page's category: a guide cut from a README, or a reference page.
GUIDE = "guide"
REFERENCE = "reference"

_HEADING = re.compile(r"(#{2,3})\s+(.+?)\s*$")


class DocsError(ValueError):
    """The SDK docs cannot be generated as the sources are."""


class Section(BaseModel):
    """One ``##`` or ``###`` heading of a page, as the site names it."""

    level: int
    id: str
    title: str


@dataclass
class Page:
    package: str
    slug: str
    title: str
    description: str
    category: str
    order: int
    body: str
    source: str = ""

    @property
    def file(self) -> str:
        return f"{self.package}/{self.slug}.md"

    def text(self) -> str:
        banner = (
            f"<!-- Generated by igni-sdk's tools/sdk_docs.py from {self.source}. "
            "Do not edit: run `make sdk-docs` in igni-sdk. -->"
        )
        return f"{banner}\n\n# {self.title}\n\n{self.body.strip()}\n"

    def sections(self) -> list[Section]:
        """Its ``##`` and ``###`` headings, as the site names them: for search, and for
        a table of contents before the page itself is loaded."""
        out: list[Section] = []
        for line, code in fenced(self.body.split("\n")):
            match = None if code else _HEADING.match(line)
            if match:
                out.append(
                    Section(
                        level=len(match.group(1)),
                        id=site_id(match.group(2)),
                        title=plain(match.group(2)),
                    )
                )
        return out


class PackageReport(BaseModel):
    """What the generator could not explain in one package, and what it counted."""

    #: Public names the code does not document.
    undocumented: int = 0
    #: The stylesheet's custom properties and classes.
    tokens: int = 0
    classes: int = 0
    #: igni-client's parameters neither the schema nor the method's doc explains.
    missing_meanings: list[str] = Field(default_factory=list)
    #: igni-client's models the contract does not describe.
    undocumented_models: int = 0

    def notes(self) -> list[str]:
        """``key: value`` for every count that is not zero, in the model's order."""
        return [f"{key}: {value}" for key, value in self.model_dump().items() if value]


@dataclass
class PackagePages:
    """One part of a package's pages, and what was counted while writing them."""

    pages: list[Page]
    report: PackageReport


def url(package: str, slug: str = "", anchor: str = "") -> str:
    """A page's path on the site; the overview is the package's own path.

    ``package`` is the name the site routes the package on
    (``Package.site``), not the name the registry knows it by.
    """
    path = f"{BASE}/{package}" + (f"/{slug}" if slug and slug != "overview" else "")
    return path + (f"#{anchor}" if anchor else "")


def docs_url(package: str) -> str:
    """The package's documentation, absolute: what its README and registry page link to."""
    return SITE + url(package)


