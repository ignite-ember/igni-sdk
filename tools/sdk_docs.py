#: How the contract's places are said in the docs: where in a message the
#: value a call is told apart by is, and where in the call it comes from.
_PLACE_TEXT = {
    "id": "the message's own id",
    "session_id": "the session the message is for",
    "run_id": "the run the message is of",
    "channel": "the channel the message is on",
}

_SOURCE_TEXT = {
    "request.id": "the id the call was sent as",
    "request.session_id": "the session the call was for",
}


def _place_text(by: str) -> str:
    """How the contract's place in a message is said."""
    if by in _PLACE_TEXT:
        return _PLACE_TEXT[by]
    if by.startswith("payload."):
        return f"the message's `{by.split('.', 1)[1]}`"
    return f"the message's `{by}`"


def _source_text(source: str) -> str:
    """How the contract's place in a call is said."""
    if source in _SOURCE_TEXT:
        return _SOURCE_TEXT[source]
    if source.startswith("args."):
        return f"the `{source.split('.', 1)[1]}` the call was given"
    if source.startswith("result."):
        return f"the `{source.split('.', 1)[1]}` the call was answered with"
    return f"the call's `{source}`"


class DocsError(ValueError):
    """The SDK docs cannot be generated as the sources are."""


@dataclass
class Page:
    package: str
    slug: str
    title: str
    description: str
    category: str
    order: int
    body: str

    @property
    def file(self) -> str:
        return f"{self.package}/{self.slug}.md"

    def text(self) -> str:
        banner = (
            f"<!-- Generated by igni-sdk's tools/sdk_docs.py from {self.source}. "
            "Do not edit: run `make sdk-docs` in igni-sdk. -->"
        )
        return f"{banner}\n\n# {self.title}\n\n{self.body.strip()}\n"

    source: str = ""

    def sections(self) -> list[dict[str, Any]]:
        """Its ``##`` and ``###`` headings, as the site names them: for search, and for
        a table of contents before the page itself is loaded."""
        out: list[dict[str, Any]] = []
        for line, code in fenced(self.body.split("\n")):
            match = None if code else re.match(r"(#{2,3})\s+(.+?)\s*$", line)
            if match:
                out.append(
                    {
                        "level": len(match.group(1)),
                        "id": site_id(match.group(2)),
                        "title": plain(match.group(2)),
                    }
                )
        return out


@dataclass(frozen=True)
class Package:
    #: The name the registry knows the package by.
    name: str
    #: The name it is imported by: ``igni_client`` for Python, the package's
    #: own name for npm.
    module: str
    #: Where the package lives in this repository.
    path: str
    #: ``python`` or ``npm``.
    kind: str = "python"
    #: The segment the site routes the package's pages on: the name for
    #: Python, a short slug for npm — a package's name carries a ``/``,
    #: which a path cannot.
    slug: str = ""
    #: The registry the package is published on.
    registry: str = "PyPI"
    #: The title its README opens with, when it is not the package's name.
    readme_title: str = ""

    @property
    def site(self) -> str:
        """The name the site routes the package's pages on."""
        return self.slug or self.name

    @property
    def install(self) -> str:
        """The line that installs the package."""
        if self.kind == "python":
            return f"pip install {self.name}"
        return f"npm install {self.name}"

    @property
    def registry_url(self) -> str:
        """The registry's own page for the package."""
        if self.kind == "python":
            return f"https://pypi.org/project/{self.name}/"
        return f"https://www.npmjs.com/package/{self.name}"


